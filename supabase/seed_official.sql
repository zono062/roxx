insert into public.posts (author_id, image_path, kind, caption, visibility, created_at)
select me.id, null, 'free', s.caption, 'public', now() - make_interval(days => s.days_ago)
from me, seed s
where not exists (
  select 1 from public.posts p where p.author_id = me.id and p.caption = s.caption
);

-- 確認用
select count(*) as "公式の投稿数"
from public.posts p join public.profiles pr on pr.id = p.author_id
where pr.handle = 'roxx_official';
